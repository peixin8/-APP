import { cleanup, render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, describe, expect, it } from 'vitest'
import App from './App'
import { emptyAppData } from './domain/types'
import { exportBackup } from './storage/fileStore'

describe('app shell and first-run experience', () => {
  afterEach(cleanup)
  it('shows local-only onboarding before data is loaded', async () => {
    render(<App />)
    expect(await screen.findByRole('heading', { name: /给工作与生活/ })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: /连接本地数据目录/ })).toBeInTheDocument()
  })
  it('imports a valid backup and exposes all nine navigation destinations', async () => {
    const user = userEvent.setup()
    const { container } = render(<App />)
    await screen.findByRole('heading', { name: /给工作与生活/ })
    const input = container.querySelector('input[type="file"]') as HTMLInputElement
    await user.upload(input, new File([exportBackup(emptyAppData())], 'backup.json', { type: 'application/json' }))
    await screen.findByRole('heading', { name: '早上好，木子' })
    for (const name of ['首页总览','今日计划','自媒体','开发工作','咨询工作','健身计划','饮食计划','游戏娱乐','数据与设置']) expect(screen.getByRole('button', { name: new RegExp(`^${name}$`) })).toBeInTheDocument()
  })
  it('renders the editorial workspace layout and dashboard card grid', async () => {
    const user = userEvent.setup()
    const { container } = render(<App />)
    await screen.findByRole('heading', { name: /给工作与生活/ })
    await user.upload(container.querySelector('input[type="file"]') as HTMLInputElement, new File([exportBackup(emptyAppData())], 'backup.json', { type: 'application/json' }))
    await screen.findByRole('heading', { name: '早上好，木子' })
    expect(container.querySelector('.app-shell')).toBeInTheDocument()
    expect(container.querySelector('.sidebar nav .nav-item.active')).toHaveTextContent('首页总览')
    expect(container.querySelector('.dashboard-grid')).toBeInTheDocument()
  })
  it('creates a dated recurring todo and tracks its completion', async () => {
    const user = userEvent.setup()
    const { container } = render(<App />)
    await screen.findByRole('heading', { name: /给工作与生活/ })
    await user.upload(container.querySelector('input[type="file"]') as HTMLInputElement, new File([exportBackup(emptyAppData())], 'backup.json', { type: 'application/json' }))
    await screen.findByRole('heading', { name: '早上好，木子' })
    await user.click(screen.getByRole('button', { name: /^今日计划$/ }))
    await user.click(screen.getByRole('button', { name: /^新增计划$/ }))
    await user.type(screen.getByPlaceholderText('例如：完成项目方案'), '晨间拉伸')
    await user.selectOptions(screen.getByLabelText('重复周期'), 'daily')
    await user.click(screen.getByRole('button', { name: '保存计划' }))
    expect(screen.getAllByText('晨间拉伸')).toHaveLength(2)
    await user.click(screen.getAllByRole('button', { name: '切换完成状态' })[0])
    expect(screen.getByRole('button', { name: '切换完成状态' })).toHaveClass('checked')
  })
  it('creates a game in its own module with a status field', async () => {
    const user = userEvent.setup()
    const { container } = render(<App />)
    await screen.findByRole('heading', { name: /给工作与生活/ })
    await user.upload(container.querySelector('input[type="file"]') as HTMLInputElement, new File([exportBackup(emptyAppData())], 'backup.json', { type: 'application/json' }))
    await screen.findByRole('heading', { name: '早上好，木子' })
    await user.click(screen.getByRole('button', { name: /^游戏娱乐$/ }))
    await user.click(screen.getByRole('button', { name: '添加游戏' }))
    await user.type(screen.getByLabelText('游戏名称'), '星露谷物语')
    await user.selectOptions(screen.getByLabelText('状态'), '在玩')
    await user.click(screen.getByRole('button', { name: '保存记录' }))
    expect(screen.getByText('星露谷物语')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: /星露谷物语/ }))
    await user.selectOptions(screen.getByLabelText('状态'), '已完成')
    await user.click(screen.getByRole('button', { name: '保存记录' }))
    expect(screen.getAllByText('已完成')).toHaveLength(2)
  })
  it('links milestones to a development project', async () => {
    const user = userEvent.setup()
    const { container } = render(<App />)
    await screen.findByRole('heading', { name: /给工作与生活/ })
    await user.upload(container.querySelector('input[type="file"]') as HTMLInputElement, new File([exportBackup(emptyAppData())], 'backup.json', { type: 'application/json' }))
    await screen.findByRole('heading', { name: '早上好，木子' })
    await user.click(screen.getByRole('button', { name: /^开发工作$/ }))
    await user.click(screen.getByRole('button', { name: '新建项目' }))
    await user.type(screen.getByLabelText('项目名称'), '个人工作台')
    await user.click(screen.getByRole('button', { name: '保存记录' }))
    await user.click(screen.getByRole('button', { name: /添加里程碑/ }))
    await user.type(screen.getByLabelText('里程碑名称'), '第一版验收')
    await user.click(screen.getByRole('button', { name: '保存记录' }))
    expect(screen.getByText('第一版验收')).toBeInTheDocument()
  })
  it('records client communication and follow-up dates', async () => {
    const user = userEvent.setup()
    const { container } = render(<App />)
    await screen.findByRole('heading', { name: /给工作与生活/ })
    await user.upload(container.querySelector('input[type="file"]') as HTMLInputElement, new File([exportBackup(emptyAppData())], 'backup.json', { type: 'application/json' }))
    await screen.findByRole('heading', { name: '早上好，木子' })
    await user.click(screen.getByRole('button', { name: /^咨询工作$/ }))
    await user.click(screen.getByRole('button', { name: '添加客户' }))
    await user.type(screen.getByLabelText('客户名称'), '林女士')
    await user.click(screen.getByRole('button', { name: '保存记录' }))
    await user.click(screen.getByRole('button', { name: '记一次沟通' }))
    await user.type(screen.getByLabelText('沟通摘要'), '讨论了下一阶段计划')
    await user.click(screen.getByRole('button', { name: '保存沟通' }))
    expect(screen.getByText(/林女士 · 讨论了下一阶段计划/)).toBeInTheDocument()
  })
})
